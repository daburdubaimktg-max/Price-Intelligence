/**
 * Simulated demo source.
 *
 * Generates the continuation of the illustrative DEMO dataset so that an evaluation installation shows a
 * living system (schedules, jobs, logs, failures, retries) without any real integration. It is NOT a
 * collection from a retailer: it never performs a network request, it only runs for retailers flagged as
 * DEMO, every observation it produces is stored with source_method = 'simulated' and is_demo = 1, and its
 * jobs carry data_class = 'simulated' so they are never counted as real collections.
 */
import type { AppContext } from '../../context.ts';
import type { CollectionMethod } from '../../../shared/constants.ts';
import type { ConnectorDescription } from '../../../shared/api/collection.ts';
import { demoObservation, keyedRandom, stateOnDay, type DemoProfile, type SimulatedConnectorConfig } from '../../seed/demo-model.ts';
import { diffDays, isIsoDate, localDate } from '../../lib/time.ts';
import { getSetting } from '../core.ts';
import { emptyResult, type CollectContext, type CollectResult, type ConfigCheck, type Connector, type SourceRetailer } from './types.ts';

export const SIMULATED_FAILURE_CODE = 'simulated_failure';

function readProfiles(raw: Record<string, unknown>): { failureRate: number; profiles: Record<string, DemoProfile> } | null {
  const simulated = (raw as Partial<SimulatedConnectorConfig>).simulated;
  if (!simulated || typeof simulated !== 'object' || !simulated.profiles || typeof simulated.profiles !== 'object') return null;
  const rate = Number(simulated.failure_rate);
  return { failureRate: Number.isFinite(rate) ? Math.min(1, Math.max(0, rate)) : 0, profiles: simulated.profiles };
}

function validProfile(p: unknown): p is DemoProfile {
  if (!p || typeof p !== 'object') return false;
  const o = p as Record<string, unknown>;
  return (
    Number.isFinite(o.seed) && Number(o.base) > 0 && Number(o.step) > 0 && Number.isFinite(o.promo) && Array.isArray(o.depths) &&
    Array.isArray(o.types) && Number.isFinite(o.drift) && Number.isFinite(o.oos)
  );
}

/**
 * Identifies one simulated run. Hour precision plus the attempt number, so an automatic retry of a
 * simulated failure is an independent draw (and can demonstrate recovery).
 */
export function simulatedRunSlot(at: Date, attempt = 1): string {
  return `${at.toISOString().slice(0, 13)}#${attempt}`;
}

/** Whether the simulated run identified by `slot` is a (clearly labelled) simulated failure. Deterministic. */
export function simulatedRunFails(retailerId: number, failureRate: number, slot: string): boolean {
  return failureRate > 0 && keyedRandom(`${retailerId}:${slot}`) < failureRate;
}

async function collectSimulated(cc: CollectContext): Promise<CollectResult> {
  const result = emptyResult();
  const settings = readProfiles(cc.config);
  const epoch = getSetting(cc.ctx, 'demo_epoch');
  if (!cc.retailer.is_demo || !settings || !epoch || !isIsoDate(epoch)) {
    result.fatal = { code: 'config_invalid', message: 'The simulated demo source is not set up (demo retailer, price profiles and demo start date are required).' };
    return result;
  }

  if (simulatedRunFails(cc.retailer.id, settings.failureRate, simulatedRunSlot(cc.now, cc.attempt))) {
    result.fatal = {
      code: SIMULATED_FAILURE_CODE,
      message: 'Simulated failure (demo): the demo generator skipped this run on purpose to demonstrate failure handling and retries. No real source was contacted.',
    };
    return result;
  }

  const observedAt = cc.now.toISOString();
  const day = Math.max(0, diffDays(epoch, localDate(cc.now, cc.retailer.timezone)));
  let evidenceIndex: number | undefined;
  for (const listing of cc.listings) {
    if (cc.signal.aborted) break;
    const profile = settings.profiles[String(listing.id)];
    if (!listing.is_demo) {
      result.outcomes.push({ listing_id: listing.id, status: 'failed', code: 'not_demo_listing', message: 'Simulated prices are only generated for DEMO listings.' });
      continue;
    }
    if (!validProfile(profile)) {
      result.outcomes.push({
        listing_id: listing.id,
        status: 'missing',
        code: 'no_simulation_profile',
        message: 'This listing has no demo price profile, so the simulated source produces nothing for it.',
      });
      continue;
    }
    if (evidenceIndex === undefined) {
      result.evidence.push({
        kind: 'simulated',
        reference: `simulated://demo-price-model/retailer/${cc.retailer.id}`,
        note: 'Generated by the deterministic demo price model. Illustrative DEMO data — not an observation of a real retailer.',
        captured_at: observedAt,
      });
      evidenceIndex = result.evidence.length - 1;
    }
    const { listing_id: _ignored, ...draft } = demoObservation(listing.id, stateOnDay(profile, day), observedAt, epoch);
    // Profiles stored before sellers were simulated name none: the demo retailer then sells the item itself.
    draft.seller_name ??= cc.retailer.name;
    result.outcomes.push({ listing_id: listing.id, status: 'ok', observation: draft, evidence: evidenceIndex, strategy: 'simulated' });
  }
  result.itemsFound = result.outcomes.filter((o) => o.status === 'ok').length;
  return result;
}

export const simulatedConnector: Connector = {
  methods: ['simulated'],
  runnable: true,
  dataClass: 'simulated',

  describe(method: CollectionMethod): ConnectorDescription {
    return {
      method,
      label: 'Simulated demo source',
      summary: 'Generates illustrative DEMO prices. Not a real integration.',
      description:
        'Keeps the DEMO dataset moving so schedules, jobs, logs, failures and retries can be explored before any real source is connected. It contacts nothing: prices come from a deterministic model and are always labelled DEMO / simulated, and its runs are never counted as real collections.',
      runnable: true,
      kind: 'simulated',
      requirements: ['A retailer that belongs to the DEMO dataset', 'Demo price profiles (created by the demo data loader)'],
      limitations: [
        'Produces fictional prices only — never use them for decisions.',
        'Cannot be used for real retailers. Switch a retailer to a real method (API, feed, permitted website extraction, third-party data, CSV or manual entry) to collect real prices.',
      ],
      credential: { needed: 'never', label: '', help: '' },
      needs_permission_attestation: false,
      supports_discovery: false,
      config_fields: [
        { key: 'simulated.failure_rate', label: 'Share of runs that fail on purpose', type: 'number', group: 'Demo behaviour', default: 0, help: 'Between 0 and 1. Simulated failures are always labelled as such.' },
      ],
      examples: [],
    };
  },

  checkConfig(ctx: AppContext, retailer: SourceRetailer, raw: Record<string, unknown>): ConfigCheck {
    const missing: string[] = [];
    if (!retailer.is_demo) missing.push('The simulated source is only available for DEMO retailers — choose a real collection method for this retailer');
    if (!readProfiles(raw)) missing.push('Demo price profiles (load the DEMO dataset in Administration)');
    const epoch = getSetting(ctx, 'demo_epoch');
    if (!epoch || !isIsoDate(epoch)) missing.push('Demo start date (set when the DEMO dataset is loaded)');
    return { ok: missing.length === 0, missing, warnings: [] };
  },

  canRunWithoutListings(): boolean {
    return false;
  },

  requestsPerListing(): boolean {
    return false;
  },

  collect: collectSimulated,
};
